bool rgblight_is_enabled(void);
void eeconfig_debug_rgblight(void);

bool process_record_user(uint16_t keycode, keyrecord_t *record) {

  // if (kbd_state == keyboard_state_waiting_for_reboot) return true;
    uprintf("process_keycode %d\n", keycode);
  switch(keycode)
  {
    // #ifdef RGBLIGHT_ENABLE
    case UG_TOGG:
    if (!record->event.pressed) {
        // 这里看起来很奇怪的，因为这是之前的状态，我们不去设置值，是后面他自己设置的
        if(rgblight_is_enabled()) {
            uprintf("rgb matrix will disabled\n");
            writePinLow(A0);
        } else {
            uprintf("rgb matrix will enabled\n");
            setPinOutput(A0);
            writePinHigh(A0);
        }
        eeconfig_debug_rgblight();
        // 只有返回true 才会继续让rgb的切换逻辑走，这样就能更新了
        return true;
    }
    // #endif
    return true;
  }
  return true;
}

void led_init_ports(void) {
#ifdef LED_NUM_LOCK_PIN
    gpio_set_pin_output_open_drain(LED_NUM_LOCK_PIN);
    gpio_write_pin(LED_NUM_LOCK_PIN, !LED_PIN_ON_STATE);
#endif
#ifdef LED_CAPS_LOCK_PIN
    gpio_set_pin_output_open_drain(LED_CAPS_LOCK_PIN);
    gpio_write_pin(LED_CAPS_LOCK_PIN, !LED_PIN_ON_STATE);
#endif
#ifdef LED_SCROLL_LOCK_PIN
    gpio_set_pin_output_open_drain(LED_SCROLL_LOCK_PIN);
    gpio_write_pin(LED_SCROLL_LOCK_PIN, !LED_PIN_ON_STATE);
#endif
#ifdef LED_COMPOSE_PIN
    gpio_set_pin_output_open_drain(LED_COMPOSE_PIN);
    gpio_write_pin(LED_COMPOSE_PIN, !LED_PIN_ON_STATE);
#endif
#ifdef LED_KANA_PIN
    gpio_set_pin_output_open_drain(LED_KANA_PIN);
    gpio_write_pin(LED_KANA_PIN, !LED_PIN_ON_STATE);
#endif
}
